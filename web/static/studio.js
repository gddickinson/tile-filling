// Studio: the desktop window (gui/app.py + gui/controls.py) in the browser. Pattern and palette pickers, the
// Rendering and Effects panels, the pattern's own sliders (from get_params()), Randomize / Regenerate, presets,
// PNG / hi-res PNG / SVG export and the 10x random batch, with the desktop key bindings.
import { route, app, esc, slider, isStatic, onLeave } from './core.js';
import { loadSetup, Generator, select, checkbox, swatches } from './data.js';
import { renderToCanvas } from './render.js';
import { randomParams } from './engine.js';
import { random } from './pyrandom.js';
import { exportPNG, exportHiRes, exportSVG, savePreset, loadPresetFile, batch, pythonRender } from './studio_io.js';

const fmt2 = v => Number(v).toFixed(2);

route('studio', async (args, query) => {
  const setup = await loadSetup();
  const { patterns, palettes, spec, bySlug } = setup;
  const first = bySlug[query.p] || patterns[0];
  const S = {                                              // ControlPanel state
    pattern: first, params: {}, palette: palettes[query.pal] ? query.pal : spec.default_palette,
    line_width: spec.line_width.default, width: spec.canvas[0], height: spec.canvas[1],
    ...Object.fromEntries(spec.toggles.map(t => [t.key, t.default])),
    kaleidoscope: spec.kaleidoscope.default, ...Object.fromEntries(spec.effects.map(t => [t.key, t.default])),
  };
  const setDefaults = () => { S.params = Object.fromEntries(S.pattern.params.map(p => [p.name, p.default])); };
  setDefaults();

  app().innerHTML = `<p class="kicker">Studio</p><h1 class="glow">Tile Filling Studio</h1>
  <p class="lead">Every control of the desktop app. Patterns are generated by a JS port of the Python generators in a
  background worker and drawn the way <code>rendering/renderer.py</code> draws them.</p>
  <div class="studio"><div class="controls" id="ctl"></div>
    <div class="view"><div class="stage"><canvas id="art" width="800" height="800" tabindex="0" role="img" aria-label="Generated pattern"></canvas></div>
    <p class="status mono" id="status" role="status">Ready</p>
    <div class="row btnrow" id="acts"></div>
    <div id="extra"></div></div></div>`;
  const ctl = document.getElementById('ctl'), art = document.getElementById('art'), status = document.getElementById('status');
  const gen = new Generator();
  onLeave(() => { gen.stop(); document.removeEventListener('keydown', onKey); });

  // --- panels -----------------------------------------------------------------------------------------------------
  const sec = title => { const d = document.createElement('fieldset'); d.innerHTML = `<legend>${esc(title)}</legend>`; ctl.appendChild(d); return d; };
  const pPat = sec('Pattern');
  const patSel = select(pPat, 'pattern', 'Pattern type', patterns.map(p => [p.slug, `${p.name}`]), S.pattern.slug, v => {
    S.pattern = bySlug[v]; setDefaults(); buildParams(); syncHash(); schedule();
  });
  const desc = document.createElement('p'); desc.className = 'small mute desc'; pPat.appendChild(desc);
  const pPal = sec('Color Palette');
  const palSel = select(pPal, 'palette', 'Palette', Object.keys(palettes), S.palette, v => { S.palette = v; showSw(); syncHash(); schedule(true); });
  const sw = document.createElement('div'); sw.className = 'sw'; pPal.appendChild(sw);
  const showSw = () => { sw.innerHTML = swatches(palettes[S.palette]); };
  showSw();

  const pRen = sec('Rendering');
  const lw = slider(pRen, { id: 'lw', label: spec.line_width.label, min: spec.line_width.min, max: spec.line_width.max, step: 0.05,
    value: S.line_width, fmt: fmt2 }, v => { S.line_width = v; schedule(true); });
  const toggles = {};
  for (const t of spec.toggles) toggles[t.key] = checkbox(pRen, `t-${t.key}`, t.label, S[t.key], v => { S[t.key] = v; schedule(true); });
  const size = document.createElement('div'); size.className = 'row size';
  size.innerHTML = `<div><label for="cw">Width (px)</label><input id="cw" type="number" min="100" max="2000" step="10" value="${S.width}"></div>
    <div><label for="ch">Height (px)</label><input id="ch" type="number" min="100" max="2000" step="10" value="${S.height}"></div>`;
  pRen.appendChild(size);
  size.addEventListener('change', () => {
    const c = v => Math.max(100, Math.min(2000, Math.round(+v || 800)));
    S.width = c(document.getElementById('cw').value); S.height = c(document.getElementById('ch').value); schedule();
  });

  const pFx = sec('Effects');
  const kal = slider(pFx, { id: 'kal', label: spec.kaleidoscope.label, min: spec.kaleidoscope.min, max: spec.kaleidoscope.max,
    value: S.kaleidoscope }, v => { S.kaleidoscope = v; schedule(true); });
  const fx = {};
  for (const t of spec.effects) fx[t.key] = checkbox(pFx, `fx-${t.key}`, t.label, S[t.key], v => { S[t.key] = v; schedule(true); });

  const pPar = sec('Pattern Parameters');
  const paramInputs = {};
  function buildParams() {
    pPar.querySelectorAll('.ctl').forEach(n => n.remove());
    desc.textContent = `${S.pattern.description}. (${S.pattern.module})`;
    patSel.value = S.pattern.slug;
    for (const p of S.pattern.params) {
      const id = `p-${p.name}`;
      if (p.type === 'bool') paramInputs[p.name] = checkbox(pPar, id, p.label, S.params[p.name], v => { S.params[p.name] = v; schedule(); });
      else {
        const isInt = p.type === 'int', step = isInt ? 1 : +((p.max - p.min) / 200).toPrecision(2);
        paramInputs[p.name] = slider(pPar, { id, label: p.label, min: p.min, max: p.max, step, value: S.params[p.name],
          fmt: isInt ? (v => v) : fmt2 }, v => { S.params[p.name] = v; schedule(); });
      }
    }
  }
  buildParams();

  // --- actions ----------------------------------------------------------------------------------------------------
  const acts = document.getElementById('acts'), extra = document.getElementById('extra');
  const btn = (label, fn, alt = true, title = '') => {
    const b = document.createElement('button'); b.type = 'button'; b.textContent = label; if (alt) b.className = 'alt';
    if (title) b.title = title; b.addEventListener('click', fn); acts.appendChild(b); return b;
  };
  const ctx = { S, setup, status, art, extra, get: () => current };
  btn('Randomize All', randomize, false, 'Space');
  btn('Regenerate', () => schedule(), true, 'R');
  btn('Save Preset', () => savePreset(ctx), true, 'S');
  const loadInput = Object.assign(document.createElement('input'), { type: 'file', accept: '.json,application/json', hidden: true });
  loadInput.setAttribute('aria-label', 'Preset file');
  acts.appendChild(loadInput);
  loadInput.addEventListener('change', async () => { if (loadInput.files[0]) await loadPresetFile(ctx, loadInput.files[0], applyState); loadInput.value = ''; });
  btn('Load Preset', () => loadInput.click(), true, 'L');
  btn('Export PNG', () => exportPNG(ctx), true, 'E');
  btn('Export Hi-Res PNG', () => exportHiRes(ctx, gen));
  btn('Export SVG', () => exportSVG(ctx), true, 'Vector lines only: the raster effects are not part of the SVG');
  btn('Batch Random (10x)', () => batch(ctx));
  if (!isStatic()) btn('Render with Python', () => pythonRender(ctx), true, 'Draw the same settings with the desktop renderer (Pillow)');

  function syncHash() {
    history.replaceState(null, '', `#/studio?p=${S.pattern.slug}&pal=${encodeURIComponent(S.palette)}`);
  }

  // Apply a preset/state to every widget (used by Load Preset).
  function applyState(p) {
    if (p.pattern) { S.pattern = p.pattern; setDefaults(); }
    Object.assign(S.params, p.params || {});
    buildParams();
    const st = p.settings || {};
    for (const k of Object.keys(st)) if (k in S && k !== 'params' && k !== 'pattern') S[k] = st[k];
    if (!palettes[S.palette]) S.palette = spec.default_palette;
    palSel.value = S.palette; showSw();
    lw.value = S.line_width; lw.dispatchEvent(new Event('input'));
    kal.value = S.kaleidoscope; kal.dispatchEvent(new Event('input'));
    for (const t of spec.toggles) toggles[t.key].checked = !!S[t.key];
    for (const t of spec.effects) fx[t.key].checked = !!S[t.key];
    syncHash(); schedule();
  }

  // TileFillingApp._randomize: every slider, then the palette.
  function randomize() {
    Object.assign(S.params, randomParams(S.pattern.params));
    S.palette = random.choice(Object.keys(palettes));
    applyState({ params: S.params, settings: { palette: S.palette } });
  }

  // --- render loop: regenerate commands when the pattern/params/size change, otherwise only redraw ------------------
  let current = null, timer = 0;
  function schedule(redrawOnly = false) {
    clearTimeout(timer);
    timer = setTimeout(() => (redrawOnly && current ? draw() : regenerate()), 50);
  }
  async function regenerate() {
    status.textContent = 'Rendering...';
    try {
      const { cmds, ms } = await gen.run(S.pattern.name, S.width, S.height, { ...S.params });
      current = { cmds, width: S.width, height: S.height, ms };
      draw();
    } catch (e) {
      if (e.message !== 'superseded') status.textContent = `Error: ${e.message}`;
    }
  }
  function draw() {
    const t0 = performance.now(), { cmds, width, height } = current;
    status.textContent = `Drawing ${cmds.length.toLocaleString('en')} elements...`;
    const img = renderToCanvas(cmds, width, height, renderOpts(S, palettes, spec));
    art.width = width; art.height = height;
    art.getContext('2d').drawImage(img, 0, 0);
    status.textContent = `Done - ${cmds.length.toLocaleString('en')} elements (generated in ${Math.round(current.ms)} ms, ` +
      `drawn in ${Math.round(performance.now() - t0)} ms)  |  R=Regen  Space=Randomize  E=Export  S=Save  L=Load`;
  }

  // Desktop key bindings (ignored while typing in a field).
  function onKey(e) {
    if (e.ctrlKey || e.metaKey || e.altKey || e.target.closest('input[type=number], input[type=text], textarea, select')) return;
    const k = e.key.toLowerCase();
    if (k === ' ' && !e.target.closest('button')) { e.preventDefault(); randomize(); }
    else if (k === 'r') schedule();
    else if (k === 'e') exportPNG(ctx);
    else if (k === 's') savePreset(ctx);
    else if (k === 'l') loadInput.click();
  }
  document.addEventListener('keydown', onKey);
  syncHash();
  regenerate();
});

export function renderOpts(S, palettes, spec) {
  const effects = { kaleidoscope: S.kaleidoscope, ...Object.fromEntries(spec.effects.map(t => [t.key, S[t.key]])) };
  return { palette: palettes[S.palette], lineWidth: S.line_width, glow: S.glow, gradient: S.gradient,
    supersample: spec.supersample, effects, strengths: spec.effect_strengths };
}
